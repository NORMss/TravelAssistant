package com.normno.travelassistant.core.ai.prompt

import com.normno.travelassistant.core.model.Trip

/**
 * Промпты лежат в одном месте и под контролем версий: это такой же код, как
 * остальной, и ломается он так же — молча и в ответе пользователю.
 */
object Prompts {

    /**
     * Общая часть для всех задач вокруг плана. Задаёт роль и, что важнее, запрещает
     * выдумывать: вымышленный адрес музея — это потерянный день поездки, а не
     * неточность в ответе.
     */
    fun planner(trip: Trip): String = """
        Ты помогаешь планировать поездку: ${trip.title}, ${trip.startDate} — ${trip.endDate}.
        Места: ${trip.destinations.joinToString(", ") { "${it.name} (${it.countryCode})" }}.
        Участников: ${trip.travellers.size.coerceAtLeast(1)}.

        Правила:
        - Не выдумывай адреса, часы работы, цены и названия. Если не уверен — скажи
          «нужно проверить» и оставь поле пустым.
        - Названия мест давай на местном языке и отдельно в понятной записи:
          местные приложения и таксисты понимают только первое.
        - Считай время переездов реалистично, с запасом на дорогу до транспорта.
        - Отвечай кратко. Это читают на телефоне, часто на ходу.
    """.trimIndent()

    /** Короткая задача для модели на устройстве: перевод фразы под ситуацию. */
    fun phrase(targetLanguage: String, situation: String): String = """
        Переведи на $targetLanguage то, что нужно сказать в ситуации: $situation.
        Верни три строки и ничего больше:
        1) перевод на $targetLanguage
        2) чтение латиницей
        3) обратный перевод на русский, чтобы было видно, что именно будет сказано
    """.trimIndent()

    /** Что делать, когда план сорвался. Ответ должен быть решением, а не рассуждением. */
    fun replan(situation: String): String = """
        Ситуация: $situation.
        Предложи два варианта, что делать, каждый одной фразой. Для каждого — чем
        придётся пожертвовать. Без вступлений.
    """.trimIndent()
}
